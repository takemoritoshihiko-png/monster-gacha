// TREASURE GACHA ビルド: src/*.js(名前順) を連結 → JSX を事前コンパイル → bundle.<hash>.js を生成し
// index.html の参照を更新する。実行: node tools/build/build.js  / 検査のみ: node tools/build/build.js --check
//
// 設計メモ:
// - sourceType:'script' 固定(旧 babel-standalone のインラインscriptと同じ非モジュール実行を保つ)
// - ファイル名にハッシュを含める(bundle.<hash>.js)。古い世代を KEEP 本残す: GitHub Pages のキャッシュで
//   古い index.html(最大10分)が生きていても、対になる旧bundleがそのまま取得でき、新旧混在が起きない。
// - バックストップ: src 1ファイル 5000 行超で警告(分割は可読性で判断=一律バックストップ規約)。
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const babel = require('@babel/core');

const ROOT = path.resolve(__dirname, '..', '..');
const SRC = path.join(ROOT, 'src');
const KEEP = 5;
const CHECK = process.argv.includes('--check');

const files = fs.readdirSync(SRC).filter(f => f.endsWith('.js')).sort();
if (files.length === 0) { console.error('src/ に .js がありません'); process.exit(1); }

let concat = '';
for (const f of files) {
  const text = fs.readFileSync(path.join(SRC, f), 'utf8');
  const lineCount = text.split('\n').length;
  if (lineCount > 5000) console.warn(`⚠ バックストップ: src/${f} が ${lineCount} 行(>5000)。可読性を確認し、分割か上限引き上げを判断すること`);
  concat += `\n// ---- src/${f} ----\n` + text + '\n';
}

// preset-env(ES5相当)を併用する理由: 旧babel-standaloneはconst/let→var等まで変換しており、
// 元コードに潜む「宣言前参照」(TDZ)がそれで隠れて動いていた(crownBonusで実測)。挙動を旧環境と
// 完全一致させるため同レベルに変換する。潜在TDZの根治は別件(backlog)。
const result = babel.transformSync(concat, {
  presets: [
    [require('@babel/preset-env'), { targets: { chrome: '40' }, modules: false }],
    [require('@babel/preset-react'), { runtime: 'classic' }],
  ],
  sourceType: 'script',
  compact: false,
  babelrc: false,
  configFile: false,
});
const code = '/* generated by tools/build/build.js — 直接編集禁止(編集は src/ へ) */\n' + result.code;
const hash = crypto.createHash('md5').update(code).digest('hex').slice(0, 8);
const bundleName = `bundle.${hash}.js`;

const htmlPath = path.join(ROOT, 'index.html');
const html = fs.readFileSync(htmlPath, 'utf8');
const newHtml = html.replace(/<script src="bundle[^"]*"><\/script>/, `<script src="${bundleName}"></script>`);
if (!/<script src="bundle[^"]*"><\/script>/.test(html)) { console.error('index.html に bundle 参照が見つかりません'); process.exit(1); }

if (CHECK) {
  const current = fs.existsSync(path.join(ROOT, bundleName));
  const refOk = newHtml === html;
  if (current && refOk) { console.log(`check OK: ${bundleName} は最新でindex.htmlの参照とも一致`); process.exit(0); }
  console.error(`check FAILED: bundleが古い/未生成です。 node tools/build/build.js を実行してからpushしてください (期待: ${bundleName})`);
  process.exit(1);
}

fs.writeFileSync(path.join(ROOT, bundleName), code, 'utf8');
fs.writeFileSync(htmlPath, newHtml, 'utf8');

// 旧世代の掃除(新しい順に KEEP 本残す)
const bundles = fs.readdirSync(ROOT).filter(f => /^bundle\.[0-9a-f]{8}\.js$/.test(f))
  .map(f => ({ f, m: fs.statSync(path.join(ROOT, f)).mtimeMs })).sort((a, b) => b.m - a.m);
for (const b of bundles.slice(KEEP)) { fs.unlinkSync(path.join(ROOT, b.f)); console.log('pruned', b.f); }

console.log(`built ${bundleName} (${Math.round(code.length / 1024)} KB, src ${files.length}ファイル) / index.html 参照更新済み`);
